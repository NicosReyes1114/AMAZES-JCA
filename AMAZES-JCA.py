class BipolarJCA:
    """Bipolar transcript integrity tag (Jump-Consistency Authentication).

    The tag is a homegrown MAC derived from the cipher's traversal path,
    computed with a single SHA-256 digest over the full ordered transcript
    of recorded events. Every event appends its fed values — the signed
    jump, the substituted character value, and the rotor shift — as
    fixed-width big-endian fields to the transcript buffer. Two bipolar
    accumulators track the traversal in parallel: the sum of all positive
    jump magnitudes and the sum of all negative jump magnitudes.

    The final tag is one SHA-256 digest of the session salt, the ordered
    transcript, both accumulators, and the event count. Because SHA-256 is
    itself a Merkle–Damgård chain, digesting the ordered transcript once
    is equivalent to chaining per event: any reordering, insertion,
    deletion, or modification of recorded events yields a completely
    different tag. The salt prefixes the transcript so the tag is bound to
    the specific session.
    """

    def __init__(self, salt: str) -> None:
        self._salt = salt
        self._transcript = bytearray()
        self._pos_sum = 0
        self._neg_sum = 0
        self._count = 0

    def record(self, salt: str, jump: int, char_val: int, current_shift: int) -> None:
        """Append one character event to the transcript and accumulators.

        Args:
            salt: Session salt (must match the salt the chain was created
                with; part of the signature for interface stability).
            jump: Signed jump value used for this character.
            char_val: Substituted character value *after* S-Box lookup and
                *before* whitening, so both directions of the mirror pass
                record identical values.
            current_shift: Rotor shift at the moment of the event.
        """
        self._transcript += struct.pack(">3i", jump, char_val, current_shift)
        if jump >= 0:
            self._pos_sum += jump
        else:
            self._neg_sum += abs(jump)
        self._count += 1

    def generate_tag(self) -> str:
        """Return the finalized 64-hex-character integrity tag.

        One SHA-256 digest over salt ‖ transcript ‖ bipolar accumulators ‖
        event count commits to the exact traversal path of the session.
        """
        h = hashlib.sha256()
        h.update(self._salt.encode())
        h.update(self._transcript)
        h.update(struct.pack(">qqq", self._pos_sum, self._neg_sum, self._count))
        return h.hexdigest().upper()


# ---------------------------------------------------------------------------
# Engine internals — each mechanism is an isolated, single-purpose function
# ---------------------------------------------------------------------------


def _whitening_mask(salt: str, current_shift: int, ptr: int) -> int:
    """Derive the per-character whitening mask.

    Args:
        salt: Session salt.
        current_shift: Cumulative geared rotor shift.
        ptr: Current key-array pointer.

    Returns:
        A mask value in ``[0, ROTOR_SIZE)``.
    """
    mask_material = f"{salt}{current_shift}{ptr}"
    return int(hashlib.sha256(mask_material.encode()).hexdigest(), 16) % ROTOR_SIZE


def _gearing_step(jump: int) -> int:
    """Compute the modular-exponentiation rotor shift step for one jump.

    Args:
        jump: Signed jump value from the key array.

    Returns:
        ``base^|jump| mod ROTOR_SIZE``.
    """
    return pow(_GEARING_BASE, abs(jump), ROTOR_SIZE)


def _subset_sum_pointer(key: list[int], salt: str) -> int:
    """Locate the starting key-array pointer via target-energy search.

    The salt is hashed into a target energy value; the key array is walked
    accumulating absolute values until the target is reached, and the
    stopping index is the starting pointer.

    Args:
        key: Shuffled signed jump array.
        salt: Session salt.

    Returns:
        The starting index into ``key``.
    """
    salt_target = int(hashlib.sha256(salt.encode()).hexdigest(), 16) % _SUBSET_SUM_TARGET_MODULUS
    running_energy = 0
    for i, val in enumerate(key):
        running_energy += abs(val)
        if running_energy >= salt_target:
            return i
    return 0


def _mutation_seed(jump: int, chars_processed: int, salt: str, sbox: list[int]) -> str:
    """Build the salt-locked, state-recursive mutation seed.

    Args:
        jump: Jump value in effect when the mutation triggered.
        chars_processed: Characters processed since the last mutation.
        salt: Session salt.
        sbox: Current rotor state (hashed recursively into the seed).

    Returns:
        The seed string for the co-evolutionary re-shuffle.
    """
    state_hash = hashlib.sha256(str(sbox).encode()).hexdigest()
    return f"{jump}{chars_processed}{salt}{state_hash}"


def _invert_sbox(sbox: list[int]) -> dict[int, int]:
    """Build the inverse rotor mapping for decryption.

    Args:
        sbox: Current rotor contents.

    Returns:
        A mapping from rotor output values back to plaintext indices.
    """
    return {v: k for k, v in enumerate(sbox)}


class AmazesEngine:
    """The stateful encryption/decryption engine.

    The engine holds all mutable session state: the substitution rotor
    (S-Box), the jump-pointer key array, the key-array pointer, the
    cumulative rotor shift, and the mutation schedule. State evolution is
    driven exclusively by key-derived values, the salt, and the number of
    characters processed — never by plaintext content — which is what makes
    deterministic state replay (the decryption "warmup") possible.
    """

    def __init__(self, sbox: list[int], key: list[int], salt: str, seed_hex: str) -> None:
        """Initialize the engine from session credentials and salt.

        Args:
            sbox: Base rotor contents (a permutation of ``0..ROTOR_SIZE-1``).
            key: Signed jump array from :func:`parse_key_string`.
            salt: Per-message session salt.
            seed_hex: Session seed as a hex string.

        Raises:
            ValueError: If ``salt`` length differs from ``SALT_SIZE``.
        """
        if len(salt) != SALT_SIZE:
            raise ValueError(f"salt must be exactly {SALT_SIZE} characters")

        normalized_seed = normalize_key_material(seed_hex, key)
        self.sbox: list[int] = deterministic_shuffle(sbox, normalized_seed)
        self.key: list[int] = deterministic_shuffle(key, normalized_seed)
        self.salt = salt
        self.jca = BipolarJCA(salt)

        self.ptr: int = _subset_sum_pointer(self.key, salt)
        self.current_shift: int = _gearing_step(self.key[self.ptr])
        seed_val = int(hashlib.sha256(normalized_seed.encode()).hexdigest(), 16)
        self.mutation_interval: int = (seed_val % 15) + 5
        self.chars_processed: int = 0

    def transform(self, text: str, encrypt: bool = True, update_jca: bool = True) -> str:
        """Transform ``text`` one pass through the engine.

        Each character is substituted through the current rotor, offset by
        the cumulative geared shift and a salt-bound whitening mask, and the
        engine state (pointer, shift, and periodically the rotor and key
        themselves) then evolves independently of the character processed.

        Args:
            text: Input string; every character must be in ``CHAR_SET``.
            encrypt: True to encrypt, False to decrypt.
            update_jca: Whether to fold events into the JCA chain. Only the
                authenticated pass of the mirror enables this.

        Returns:
            The transformed string of the same length as ``text``.

        Raises:
            ValueError: If ``text`` contains a character outside
                ``CHAR_SET``.
        """
        res: list[str] = []
        inv_sbox: dict[int, int] | None = _invert_sbox(self.sbox) if not encrypt else None

        for char in text:
            if char not in C2I:
                raise ValueError(f"character outside printable ASCII set: {char!r}")

            jump = self.key[self.ptr]
            self.current_shift = (self.current_shift + _gearing_step(jump)) % ROTOR_SIZE
            whitening_mask = _whitening_mask(self.salt, self.current_shift, self.ptr)

            if encrypt:
                sub_val = self.sbox[C2I[char]]
                if update_jca:
                    self.jca.record(self.salt, jump, sub_val, self.current_shift)
                out_val = (sub_val + self.current_shift + whitening_mask) % ROTOR_SIZE
            else:
                sub_val = (C2I[char] - whitening_mask - self.current_shift) % ROTOR_SIZE
                if update_jca:
                    self.jca.record(self.salt, jump, sub_val, self.current_shift)
                out_val = inv_sbox[sub_val]
            res.append(I2C[out_val])

            # Co-evolutionary mutation: after the interval elapses, both the
            # rotor and the key array are re-shuffled from a salt-locked seed
            # that recursively hashes the current rotor state.
            self.chars_processed += 1
            if self.chars_processed >= self.mutation_interval:
                m_seed = _mutation_seed(jump, self.chars_processed, self.salt, self.sbox)
                self.sbox = deterministic_shuffle(self.sbox, m_seed)
                self.key = deterministic_shuffle(self.key, m_seed)
                self.mutation_interval = (abs(jump) % 15) + 5
                self.chars_processed = 0
                if not encrypt:
                    inv_sbox = _invert_sbox(self.sbox)

            self.ptr = (self.ptr + abs(jump)) % KEY_SIZE

        return "".join(res)


