# CLI
# ---------------------------------------------------------------------------


def main() -> None:
    """Interactive CLI: generate session credentials and encrypt/decrypt messages."""
    base_seed, session_key_str = generate_session_credentials()
    session_key_ints = parse_key_string(session_key_str)

    while True:
        print("\n" + "=" * 65)
        print("AMAZES-JCA (Full-Hardened) — educational cipher, not for production")
        print(f"SESSION SEED: {base_seed}")
        print(f"SESSION KEY:  {session_key_str}")
        print("=" * 65)

        cmd = input("[E]ncrypt, [D]ecrypt, [Exit]: ").strip().lower()
        if cmd == "exit":
            break
        if cmd == "e":
            text = input("Enter Message: ")
            try:
                package, _ = run_amazes(text, base_seed, session_key_ints, encrypt=True)
                print(f"\nOUTPUT: {package}")
            except ValueError as exc:
                print(f"\nERROR: {exc}")
        elif cmd == "d":
            creds = input("Credentials [Seed/Key] (Enter for current): ").strip()
            if creds:
                try:
                    seed_str, key_str = creds.split("/")
                    seed, key_ints = seed_str, parse_key_string(key_str)
                except ValueError as exc:
                    print(f"Invalid credential format: {exc}")
                    continue
            else:
                seed, key_ints = base_seed, session_key_ints
            package = input("Enter Full Package: ")
            try:
                plain, valid = run_amazes(package, seed, key_ints, encrypt=False)
            except ValueError as exc:
                print(f"\nERROR: {exc}")
                continue
            print(f"\nJCA STATUS: {'VALID' if valid else 'INVALID'}")
            if valid:
                print(f"RESULT: {plain}")


if __name__ == "__main__":
    main()