def pack_package(salt: str, ciphertext: str, tag: str) -> str:
    """Assemble a transmittable package from its components.

    Args:
        salt: Session salt (``SALT_SIZE`` characters).
        ciphertext: Ciphertext body.
        tag: JCA integrity tag (``TAG_SIZE`` hex characters).

    Returns:
        ``salt || ciphertext || tag``.
    """
    return f"{salt}{ciphertext}{tag}"


def unpack_package(package: str) -> tuple[str, str, str]:
    """Split a package into salt, ciphertext, and tag.

    Args:
        package: Full package string.

    Returns:
        A ``(salt, ciphertext, tag)`` tuple.

    Raises:
        ValueError: If the package is too short to contain salt,
            ciphertext, and tag.
    """
    if len(package) < SALT_SIZE + TAG_SIZE:
        raise ValueError("package too short to contain salt, ciphertext, and tag")
    return package[:SALT_SIZE], package[SALT_SIZE:-TAG_SIZE], package[-TAG_SIZE:]


# ---------------------------------------------------------------------------
# Message operations — encryption and decryption are independent procedures
# ---------------------------------------------------------------------------


def _validate_salt(salt: str) -> None:
    """Validate a caller-supplied salt.

    Args:
        salt: Salt string to validate.

    Raises:
        ValueError: If the salt length or character set is wrong.
    """
    if len(salt) != SALT_SIZE or any(c not in C2I for c in salt):
        raise ValueError(f"salt must be {SALT_SIZE} characters from CHAR_SET")


def encrypt_message(text: str, seed_hex: str, key_ints: list[int], salt: str | None = None) -> str:
    """Encrypt one plaintext message into a full package.

    Runs the two-pass mirror: a forward pass over the plaintext
    (unauthenticated), then a reflection pass over the reversed intermediate
    text starting from the engine's hot state (authenticated by the JCA
    chain).

    Args:
        text: Plaintext; every character must be in ``CHAR_SET``.
        seed_hex: Session seed as a hex string.
        key_ints: Signed jump array from :func:`parse_key_string`.
        salt: Optional pre-set salt for deterministic/reproducible testing.
            When ``None`` (the default) a fresh random salt is generated.

    Returns:
        The package ``salt || ciphertext || tag``.

    Raises:
        ValueError: If input contains characters outside ``CHAR_SET``, or a
            supplied salt has the wrong length or character set.
    """
    if salt is None:
        salt = generate_salt()
    else:
        _validate_salt(salt)

    base_sbox = list(range(ROTOR_SIZE))
    engine = AmazesEngine(base_sbox, key_ints, salt, seed_hex)
    c1 = engine.transform(text, encrypt=True, update_jca=False)
    c2 = engine.transform(c1[::-1], encrypt=True, update_jca=True)
    return pack_package(salt, c2[::-1], engine.jca.generate_tag())


def _replay_hot_state(seed_hex: str, key_ints: list[int], salt: str, length: int) -> AmazesEngine:
    """Reconstruct the encryption engine's hot state by warmup replay.

    The state schedule is plaintext-independent, so transforming filler of
    the same length as the forward pass reproduces the hot state exactly.

    Args:
        seed_hex: Session seed as a hex string.
        key_ints: Signed jump array.
        salt: Session salt.
        length: Number of characters the forward pass processed.

    Returns:
        The engine positioned at the hot state.
    """
    engine = AmazesEngine(list(range(ROTOR_SIZE)), key_ints, salt, seed_hex)
    _ = engine.transform(" " * length, encrypt=True, update_jca=False)
    return engine


def decrypt_message(package: str, seed_hex: str, key_ints: list[int]) -> tuple[str | None, bool]:
    """Decrypt one package and verify its JCA tag.

    Decryption reverses the reflection pass from a replayed hot state
    (recording JCA events), then reverses the forward pass.

    Args:
        package: Full package string.
        seed_hex: Session seed as a hex string.
        key_ints: Signed jump array from :func:`parse_key_string`.

    Returns:
        ``(plaintext, True)`` if the JCA tag verifies, else
        ``(None, False)``.

    Raises:
        ValueError: If the package is too short to contain salt,
            ciphertext, and tag.
    """
    salt, ciphertext, tag_received = unpack_package(package)

    engine = _replay_hot_state(seed_hex, key_ints, salt, len(ciphertext))
    p2 = engine.transform(ciphertext[::-1], encrypt=False, update_jca=True)

    engine_final = AmazesEngine(list(range(ROTOR_SIZE)), key_ints, salt, seed_hex)
    plaintext = engine_final.transform(p2[::-1], encrypt=False, update_jca=False)

    valid = hmac.compare_digest(engine.jca.generate_tag(), tag_received)
    return (plaintext if valid else None), valid


def run_amazes(
    text: str,
    seed_hex: str,
    key_ints: list[int],
    encrypt: bool = True,
    salt: str | None = None,
) -> tuple[str | None, bool]:
    """Encrypt or decrypt one complete message package.

    Compatibility dispatcher over :func:`encrypt_message` and
    :func:`decrypt_message`.

    Args:
        text: Plaintext to encrypt, or a full package to decrypt.
        seed_hex: Session seed as a hex string.
        key_ints: Signed jump array from :func:`parse_key_string`.
        encrypt: True to encrypt, False to decrypt.
        salt: Optional pre-set salt for deterministic/reproducible testing
            (ignored when decrypting).

    Returns:
        ``(package, True)`` when encrypting. When decrypting:
        ``(plaintext, True)`` if the JCA tag verifies, else ``(None, False)``.

    Raises:
        ValueError: If input contains characters outside ``CHAR_SET``, or a
            package to decrypt is too short to contain salt, ciphertext,
            and tag.
    """
    if encrypt:
        return encrypt_message(text, seed_hex, key_ints, salt=salt), True
    return decrypt_message(text, seed_hex, key_ints)


