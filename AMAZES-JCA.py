"""AMAZES-JCA (Full-Hardened) — a stateful, mutating, polyalphabetic ASCII cipher.

AMAZES-JCA is an educational symmetric cipher operating on the 95 printable
ASCII characters. It combines a keyed substitution rotor (S-Box), a signed
jump-pointer key array, per-character whitening, co-evolutionary state
mutation, and a two-pass "mirror" encryption process, authenticated by a
chained-hash integrity tag (JCA).

Design goals
------------
* Entirely homegrown construction: every mechanism (substitution rotor,
  jump pointers, whitening, mutation schedule, integrity chain) is built
  from SHA-256 and modular arithmetic only. No standard AEAD primitives
  (HMAC, Poly1305, GCM) are used.
* Deterministic decryption via state replay: the decryption side
  reconstructs the encryption engine's "hot state" by re-running the
  plaintext-independent state schedule.
* Credential separation: the session seed and the key are generated by
  independent functions, so in a zero-trust setup separate devices can
  each generate exactly one of the two components.

Security status (read this first)
---------------------------------
This cipher is a design study, NOT a production cipher. It has no security
proof, has not undergone public cryptanalysis, and must not be used to
protect real data. For real workloads use AES-GCM or ChaCha20-Poly1305 from
a maintained library (e.g. ``cryptography``).

Package format
--------------
``salt (8 chars) || ciphertext (n chars) || JCA tag (64 hex chars)``

Salt and tag are transmitted in clear; the session secret is the pair
``(seed_hex, key_hex)``.

Authorship note
---------------
Original concept and iterative design by the project author in
collaboration with AI tooling; this cleaned implementation retains the
Full-Hardened mechanics: subset-sum pointer initialization, modular
exponentiation gearing, whitening masks, salt-locked recursive state
mutation, the two-pass mirror, and the chained JCA tag.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets
import struct

CHAR_SET: list[str] = [chr(i) for i in range(32, 127)]
"""The 95 printable ASCII characters (decimal 32-126) the cipher operates on."""

ROTOR_SIZE: int = len(CHAR_SET)
"""Size of the substitution rotor (S-Box)."""

KEY_SIZE: int = 64
"""Number of signed jump entries in the key array."""

SALT_SIZE: int = 8
"""Length of the per-message session salt, in characters."""

TAG_SIZE: int = 64
"""Length of the JCA integrity tag, in hex characters."""

SEED_BYTES: int = 16
"""Length of the session seed in bytes (128 bits)."""

KEY_BYTES: int = 32
"""Length of the key string in bytes (256 bits) before digit expansion."""

_GEARING_BASE: int = 3
"""Base used for modular-exponentiation rotor gearing."""

_SUBSET_SUM_TARGET_MODULUS: int = 500
"""Upper bound (exclusive) of the subset-sum target energy derived from the salt."""

_HEX_DIGITS = frozenset("0123456789abcdefABCDEF")

C2I: dict[str, int] = {c: i for i, c in enumerate(CHAR_SET)}
I2C: dict[int, str] = {i: c for i, c in enumerate(CHAR_SET)}


# ---------------------------------------------------------------------------
# Credential generation — each component is generated independently so a
# zero-trust deployment can assign one generator per device.
# ---------------------------------------------------------------------------


def generate_seed() -> str:
    """Generate a fresh session seed.

    Returns:
        A 128-bit hex string suitable for use as ``seed_hex``.
    """
    return secrets.token_hex(SEED_BYTES)


def generate_key_string() -> str:
    """Generate a fresh key string.

    Returns:
        An uppercase 256-bit hex string suitable for
        :func:`parse_key_string`.
    """
    return secrets.token_hex(KEY_BYTES).upper()


def generate_session_credentials() -> tuple[str, str]:
    """Generate a fresh session seed and key string together.

    Convenience composition of :func:`generate_seed` and
    :func:`generate_key_string` for callers that generate both components
    on one device.

    Returns:
        A ``(seed_hex, key_hex)`` pair.
    """
    return generate_seed(), generate_key_string()


def generate_salt() -> str:
    """Generate a fresh random per-message session salt.

    Returns:
        A string of ``SALT_SIZE`` random characters from ``CHAR_SET``.
    """
    return "".join(secrets.choice(CHAR_SET) for _ in range(SALT_SIZE))


# ---------------------------------------------------------------------------
# Key material utilities
# ---------------------------------------------------------------------------


def parse_key_string(hex_key: str) -> list[int]:
    """Convert a hexadecimal key string into the signed jump array.

    Each hex digit maps to one signed entry: ``0-7`` map to themselves and
    ``8-f`` map to ``-1..-8``. The array is extended by repetition to
    ``KEY_SIZE`` entries (or truncated to it).

    Args:
        hex_key: Hexadecimal string; every character must be a hex digit.

    Returns:
        A list of ``KEY_SIZE`` signed integers in ``[-8, 7]``.

    Raises:
        ValueError: If ``hex_key`` is empty or contains non-hex characters.
    """
    hex_key = hex_key.strip()
    if not hex_key or any(c not in _HEX_DIGITS for c in hex_key):
        raise ValueError("key must be a non-empty hexadecimal string")
    integers = [int(c, 16) for c in hex_key]
    integers = [v if v < 8 else -(v - 7) for v in integers]
    while len(integers) < KEY_SIZE:
        integers.extend(integers[: len(integers)])
    return integers[:KEY_SIZE]


def normalize_key_material(seed_hex: str, key_ints: list[int]) -> str:
    """Mix the session seed and key array into a single 256-bit seed.

    Both the rotor shuffle and the key shuffle derive from this normalized
    seed, so the seed and key only ever need to be transmitted/stored as a
    pair and never used raw.

    Args:
        seed_hex: Session seed as a hex string.
        key_ints: Signed jump array.

    Returns:
        A 64-character hex digest binding seed and key.
    """
    combined = f"{seed_hex}{key_ints}".encode()
    return hashlib.sha256(combined).hexdigest()


def deterministic_shuffle(elements: list, seed_string: str) -> list:
    """Shuffle ``elements`` deterministically, driven by ``seed_string``.

    Implements a Fisher-Yates shuffle where the swap strides come from a
    SHA-256 digest chain seeded by ``seed_string``. The digest is refreshed
    every 16 draws so shuffles of any length stay deterministic.

    Args:
        elements: Sequence to shuffle (copied; the input is not modified).
        seed_string: String hashed to seed the shuffle.

    Returns:
        A new shuffled list.
    """
    shuffled = list(elements)
    entropy = hashlib.sha256(seed_string.encode()).digest()
    for i in range(len(shuffled) - 1, 0, -1):
        if i % 16 == 0:
            entropy = hashlib.sha256(entropy).digest()
        stride = int.from_bytes(entropy[i % 16 : i % 16 + 2], "big")
        j = stride % (i + 1)
        shuffled[i], shuffled[j] = shuffled[j], shuffled[i]
    return shuffled


